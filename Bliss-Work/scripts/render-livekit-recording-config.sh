#!/usr/bin/env bash
#
# Render the SFU config used when call recording is ON.
#
# ── Why this exists ─────────────────────────────────────────────────────────
# Recording needs one block in the SFU config that the tracked file cannot
# carry: a Redis password. `infra/livekit/livekit.yaml` is IN THE REPO — its own
# header says the keys are passed by environment "so the secret never lands on
# disk in the image or the repo", and pasting a password in by hand (which
# docs/RECORDING.md used to ask for) undoes exactly that.
#
# So the tracked file stays the reviewable, secret-free source, and this script
# appends the secret-bearing block to a gitignored copy that only ever exists on
# the deployment host. Same reasoning as EGRESS_CONFIG_BODY in
# docker-compose.recording.yml, which inlines the egress config for the same
# reason.
#
# The `webhook:` block USED to be appended here too, and that was the bug this
# script is no longer party to: it made room-lifecycle callbacks a property of
# recording, so any deploy that brought `livekit` up without the recording
# overlay silently reverted the SFU to a config with no callbacks at all, and
# hostless meetings stopped ending. Webhooks need no Redis; they now live in the
# tracked base config, with the api_key coming from LIVEKIT_WEBHOOK_API_KEY.
#
# Usage (from the repo's Bliss-Work directory):
#   set -a; . ./.env; . ./.env.prod; set +a
#   bash scripts/render-livekit-recording-config.sh
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
src="$here/infra/livekit/livekit.yaml"
out="$here/infra/livekit/livekit.recording.yaml"

# Fail closed. A missing value would render a config the SFU either rejects at
# startup (taking every call down with it) or, worse, accepts with an empty
# password — an unauthenticated Redis holding the room state.
missing=()
for var in REDIS_PASSWORD; do
  [[ -n "${!var:-}" ]] || missing+=("$var")
done
if (( ${#missing[@]} )); then
  echo "render-livekit-recording-config: missing ${missing[*]}" >&2
  echo "  source BOTH env files first: set -a; . ./.env; . ./.env.prod; set +a" >&2
  exit 1
fi

[[ -f "$src" ]] || { echo "no such file: $src" >&2; exit 1; }

# The template must not already define this, or the SFU sees a duplicate key.
# `webhook:` deliberately IS in the template now and must be left alone.
if grep -qE '^redis:' "$src"; then
  echo "render-livekit-recording-config: $src already defines redis:." >&2
  echo "  This script APPENDS it; remove it from the tracked file." >&2
  exit 1
fi
# The reverse check. Recording used to bring the callbacks with it; now the base
# config carries them and this only adds Redis. A template that lost the block
# would render an SFU that records but never reports a departure.
if ! grep -qE '^webhook:' "$src"; then
  echo "render-livekit-recording-config: $src defines no webhook: block." >&2
  echo "  Room-lifecycle callbacks belong in the tracked base config now." >&2
  exit 1
fi

umask 077   # the output holds secrets; never world-readable
{
  cat "$src"
  cat <<YAML

# ─────────────────────────────────────────────────────────────────────────────
# GENERATED by scripts/render-livekit-recording-config.sh — DO NOT EDIT, and do
# not commit: this file holds the Redis password.
# Re-render it after any change to infra/livekit/livekit.yaml, and RECREATE the
# container afterwards — a bind-mounted single file is not re-read on restart.
#
# The webhook: block above came from the tracked base config and is NOT specific
# to recording — egress reports finished files over the same callback the room
# lifecycle already uses.
# ─────────────────────────────────────────────────────────────────────────────

# This container is host-networked, so it cannot resolve \`redis\` on the compose
# bridge; the overlay publishes Redis on loopback for exactly this line.
redis:
  address: 127.0.0.1:6379
  password: ${REDIS_PASSWORD}
YAML
} > "$out"

echo "wrote $out ($(wc -l < "$out") lines, mode $(stat -c %a "$out"))"
