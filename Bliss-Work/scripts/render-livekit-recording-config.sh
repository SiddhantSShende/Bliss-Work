#!/usr/bin/env bash
#
# Render the SFU config used when call recording is ON.
#
# ── Why this exists ─────────────────────────────────────────────────────────
# Recording needs two blocks in the SFU config that the tracked file cannot
# carry: a Redis password and the LiveKit API key. `infra/livekit/livekit.yaml`
# is IN THE REPO — its own header says the keys are passed by environment "so
# the secret never lands on disk in the image or the repo", and pasting them in
# by hand (which docs/RECORDING.md used to ask for) undoes exactly that.
#
# So the tracked file stays the reviewable, secret-free source, and this script
# appends the two secret-bearing blocks to a gitignored copy that only ever
# exists on the deployment host. Same reasoning as EGRESS_CONFIG_BODY in
# docker-compose.recording.yml, which inlines the egress config for the same
# reason.
#
# Usage (from the repo's Bliss-Work directory):
#   set -a; . ./.env; . ./.env.prod; set +a
#   bash scripts/render-livekit-recording-config.sh
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
src="$here/infra/livekit/livekit.yaml"
out="$here/infra/livekit/livekit.recording.yaml"

# Fail closed. A missing value would render a config the SFU either rejects at
# startup (taking every call down with it) or, worse, accepts with an empty
# password — an unauthenticated Redis holding the room state.
missing=()
for var in REDIS_PASSWORD LIVEKIT_API_KEY DOMAIN; do
  [[ -n "${!var:-}" ]] || missing+=("$var")
done
if (( ${#missing[@]} )); then
  echo "render-livekit-recording-config: missing ${missing[*]}" >&2
  echo "  source BOTH env files first: set -a; . ./.env; . ./.env.prod; set +a" >&2
  exit 1
fi

[[ -f "$src" ]] || { echo "no such file: $src" >&2; exit 1; }

# The template must not already define these, or the SFU sees a duplicate key.
if grep -qE '^(redis|webhook):' "$src"; then
  echo "render-livekit-recording-config: $src already defines redis:/webhook:." >&2
  echo "  This script APPENDS them; remove them from the tracked file." >&2
  exit 1
fi

umask 077   # the output holds secrets; never world-readable
{
  cat "$src"
  cat <<YAML

# ─────────────────────────────────────────────────────────────────────────────
# GENERATED by scripts/render-livekit-recording-config.sh — DO NOT EDIT, and do
# not commit: this file holds the Redis password and the LiveKit API key.
# Re-render it after any change to infra/livekit/livekit.yaml, and RECREATE the
# container afterwards — a bind-mounted single file is not re-read on restart.
# ─────────────────────────────────────────────────────────────────────────────

# This container is host-networked, so it cannot resolve \`redis\` on the compose
# bridge; the overlay publishes Redis on loopback for exactly this line.
redis:
  address: 127.0.0.1:6379
  password: ${REDIS_PASSWORD}

webhook:
  # Signs the callback with the same key pair as the room tokens; messaging-svc
  # verifies that signature over the body before believing any of it.
  api_key: ${LIVEKIT_API_KEY}
  urls:
    # NOT /livekit/webhook — the edge proxies /livekit/* to THIS server, so that
    # URL posts the callback back to the SFU and the recording sits in RECORDING
    # for ever. messaging-svc is reached under /api/messaging, which Caddy strips.
    - https://${DOMAIN}/api/messaging/livekit/webhook
YAML
} > "$out"

echo "wrote $out ($(wc -l < "$out") lines, mode $(stat -c %a "$out"))"
